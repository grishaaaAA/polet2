"""
Базовый вариант, с которым мы себя сравниваем.

Цитата, по которой это написано (приписана разделу 2.3 ТЗ):

    «Для единого сравнения базовый вариант задаётся так: заявки
    обрабатываются по порядку поступления и назначаются первому по
    порядку во входных данных доступному инженеру, который удовлетворяет
    обязательным ограничениям; порядок посещения соответствует порядку
    назначения. Глобальная оптимизация в базовом варианте не
    выполняется.»

**Эту цитату нечем подтвердить, и это надо знать.** Самого ТЗ в
репозитории нет — ни файла, ни в архивах передач. Строка «Для единого
сравнения» встречается на всём диске ровно один раз: здесь. А
сохранённая запись сессии вопросов отвечает иначе: ментор спросил, что
считать базлайном, представитель постановщика открыл раздел 2.3 вживую и
сказал — «что является базовым сценарием: базового сценария так такового
нет… более того, понятие базы, ну, я здесь не вижу; качество будет
определяться по оптимальности маршрутов, по тому, сколько исполнителей
задействовано, сколько заявок распределено» (00:26:36).

Возможны оба объяснения: цитата верна и взята из текста ТЗ, которого у
нас под рукой нет, — или это наша формулировка, обросшая кавычками.
Проверяется открытием ТЗ, раздел 2.3, и это надо сделать до защиты.

Пока не проверено, честная формулировка на защите такая: **это не «база
из ТЗ», а понятный и воспроизводимый способ показать, чего стоит
планирование** — распределение без всякой оптимизации, по порядку
поступления. Заявленное сравнение от этого не рушится: 96 из 110,6
лишних назначенных заявок даёт уже одна сортировка входа, и это стоит
сказать самим, не дожидаясь вопроса.

Три слова здесь несут всю нагрузку, и каждое отличает этот планировщик
от нашего `greedy.py`:

* **по порядку поступления** — заявки не сортируются вообще. `greedy`
  сортирует по началу окна, и уже одним этим он заметно сильнее;
* **первому доступному** — не самому дешёвому. `greedy` перебирает всех
  и берёт того, кому вставка обойдётся дешевле;
* **порядок посещения соответствует порядку назначения** — заявка
  дописывается в хвост маршрута, менять местами ничего нельзя.

Поэтому `greedy` на роль базового варианта не годится: сравнение с ним
польстило бы базовому варианту и занизило наш выигрыш, а сравнение
требуется именно с тем, что описано в ТЗ.

Это и есть та точка отсчёта, относительно которой считаются обе
обязательные метрики: число задействованных исполнителей и пробег.
"""

from __future__ import annotations

from ..core.domain import Day, Plan, require_valid
from .base import make_route, schedule


def solve(day: Day) -> Plan:
    """
    Последовательное распределение. Никакой оптимизации.

    Порядок инженеров — тот, в котором они пришли во входных данных:
    ТЗ говорит «первому по порядку во входных данных», а не «первому
    свободному» и не «ближайшему».
    """
    net = day.network
    seqs: dict[str, list] = {e.id: [] for e in day.engineers}
    visits: dict[str, list] = {e.id: [] for e in day.engineers}
    engineers = {e.id: e for e in day.engineers}

    unassigned = []

    for order in day.orders:                    # порядок поступления, как есть
        placed = False

        for eng in day.engineers:               # порядок во входных данных
            # Квалификация и транспорт — две из трёх обязательных групп.
            if not eng.can_do(order):
                continue

            # Третья группа, время: заявка дописывается в хвост, и если
            # так она не укладывается — этот инженер не подходит.
            # Переставлять визиты местами базовому варианту нельзя.
            candidate = schedule(eng, seqs[eng.id] + [order], net)
            if candidate is None:
                continue

            seqs[eng.id].append(order)
            visits[eng.id] = candidate
            placed = True
            break                               # первый подходящий, а не лучший

        if not placed:
            unassigned.append(order)

    return require_valid(Plan(
        routes={eid: make_route(engineers[eid], v)
                for eid, v in visits.items() if v},
        unassigned=unassigned,
    ), day, "базовый план невалиден")
